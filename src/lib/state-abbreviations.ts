export function getStateAbbreviation(stateName: string): string {
  return stateAbbreviations[stateName] ?? stateName.slice(0, 2).toUpperCase();
}

export function formatStateLabel(fullName: string, abbreviation?: string): string {
  const abbr = abbreviation ?? getStateAbbreviation(fullName);
  return `${fullName} (${abbr})`;
}

export const stateOptions = usStates.map((state) => ({
  fullName: state,
  abbreviation: getStateAbbreviation(state),
  label: formatStateLabel(state, getStateAbbreviation(state)),
}));
